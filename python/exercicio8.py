"""Exercício 08.

Cálculo de Salário
Elabore um programa que calcule o salário mensal de uma pessoa, com base nas horas
trabalhadas por mês e no valor por hora.
"""

horas = int(input("DIgite a quantida de horas teabalhadas no mês: "))
salario = int(input("Digite seu salário: "))

calculo_mes = salario  * horas

print(calculo_mes)